/**
 * The only skin Atlas ships.
 *
 * There used to be six. They were a personalisation feature from the upstream
 * app, and they carried a Nous-branded default — which is neither the product
 * being sold nor a choice worth asking a customer to make. Mono is grayscale,
 * reads well in both light and dark, and needs no accent decision from anyone.
 *
 * The retired names still resolve: RETIRED_SKINS in context.tsx maps a
 * persisted 'nous' or 'ember' onto this one, so an existing install keeps
 * working through the upgrade instead of booting to a blank palette.
 */
export const BUILTIN_THEMES: Record<string, DesktopTheme> = {
  mono: monoTheme
}

export const BUILTIN_THEME_LIST = Object.values(BUILTIN_THEMES)

/** Skin used when nothing is persisted or the persisted name is retired. */
export const DEFAULT_SKIN_NAME = 'mono'
